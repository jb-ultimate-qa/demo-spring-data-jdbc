-- basic model

CREATE TABLE book
(
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    title  VARCHAR,
    author VARCHAR,
    CONSTRAINT pk_book PRIMARY KEY (id)
);

CREATE TABLE customers
(
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    full_name   VARCHAR,
    email       VARCHAR,
    city        VARCHAR,
    CONSTRAINT pk_customers PRIMARY KEY (customer_id)
);

CREATE TABLE users
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    username          VARCHAR,
    city              VARCHAR,
    street            VARCHAR,
    passport_number   VARCHAR,
    passport_is_valid BOOLEAN,
    CONSTRAINT pk_users PRIMARY KEY (id)
);

CREATE TABLE buyers
(
    buyer_id  BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    full_name VARCHAR,
    CONSTRAINT pk_buyers PRIMARY KEY (buyer_id)
);

CREATE TABLE order_items
(
    product_id BIGINT,
    quantity   INTEGER,
    order_id   BIGINT NOT NULL,
    orders_key VARCHAR
);

CREATE TABLE orders
(
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    buyer_id BIGINT,
    shop     INTEGER,
    CONSTRAINT pk_orders PRIMARY KEY (id)
);

CREATE TABLE products
(
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name  VARCHAR,
    price DECIMAL,
    CONSTRAINT pk_products PRIMARY KEY (id)
);

CREATE TABLE shops
(
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    shop_name VARCHAR,
    CONSTRAINT pk_shops PRIMARY KEY (id)
);

ALTER TABLE order_items
    ADD CONSTRAINT fk_order_items_on_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE;

ALTER TABLE orders
    ADD CONSTRAINT fk_orders_on_shop FOREIGN KEY (shop) REFERENCES shops (id) ON DELETE CASCADE;

CREATE TABLE box
(
    id     INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    volume DOUBLE PRECISION,
    CONSTRAINT pk_box PRIMARY KEY (id)
);

CREATE TABLE item1
(
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name1    VARCHAR,
    box1_id  INTEGER                                  NOT NULL,
    list_key VARCHAR,
    CONSTRAINT pk_item1 PRIMARY KEY (id)
);

CREATE TABLE item2
(
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name2   VARCHAR,
    box2_id INTEGER                                  NOT NULL,
    CONSTRAINT pk_item2 PRIMARY KEY (id)
);

CREATE TABLE item3
(
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name3   VARCHAR,
    box3_id INTEGER                                  NOT NULL,
    map_key VARCHAR,
    CONSTRAINT pk_item3 PRIMARY KEY (id)
);

ALTER TABLE item1
    ADD CONSTRAINT fk_item1_on_box1 FOREIGN KEY (box1_id) REFERENCES box (id) ON DELETE CASCADE;

ALTER TABLE item2
    ADD CONSTRAINT fk_item2_on_box2 FOREIGN KEY (box2_id) REFERENCES box (id) ON DELETE CASCADE;

ALTER TABLE item3
    ADD CONSTRAINT fk_item3_on_box3 FOREIGN KEY (box3_id) REFERENCES box (id) ON DELETE CASCADE;


-- Composite id

CREATE TABLE complicated_entity
(
    id_numeric  BIGINT  NOT NULL,
    id_extended VARCHAR NOT NULL,
    name        VARCHAR,
    CONSTRAINT pk_complicated_entity PRIMARY KEY (id_numeric, id_extended)
);

CREATE TABLE complicated_record
(
    id_num      BIGINT  NOT NULL,
    id_ext      VARCHAR NOT NULL,
    description VARCHAR,
    CONSTRAINT pk_complicated_record PRIMARY KEY (id_num, id_ext)
);

CREATE TABLE item_a
(
    id    INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    namea VARCHAR,
    CONSTRAINT pk_item_a PRIMARY KEY (id)
);

CREATE TABLE item_b
(
    id    INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nameb VARCHAR,
    CONSTRAINT pk_item_b PRIMARY KEY (id)
);

CREATE TABLE item_c
(
    id    INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    namec VARCHAR,
    CONSTRAINT pk_item_c PRIMARY KEY (id)
);

